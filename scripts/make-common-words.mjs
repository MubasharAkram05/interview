// Builds src/data/common-words.js: about 11,000 common English words (SCOWL size 10 and 20,
// via the wordlist-english package, MIT; SCOWL copyright in src/data/COMMON-WORDS-LICENSE.txt).
// Voice correction never "fixes" a word on this list. Run: node scripts/make-common-words.mjs
import { createRequire } from 'node:module';
import { writeFileSync, copyFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const parts = ['english-words-10', 'english-words-20', 'american-words-10', 'american-words-20', 'british-words-10', 'british-words-20'];
const set = new Set();
for (const p of parts) for (const w of require(`wordlist-english/${p}.json`)) if (/^[a-z]+$/.test(w)) set.add(w);
const words = [...set].sort();
const out = `// Generated by scripts/make-common-words.mjs. Do not edit by hand.
// ${words.length} common English words from SCOWL (sizes 10 and 20). Licence: see COMMON-WORDS-LICENSE.txt.
export default ${JSON.stringify(words.join(' '))};
`;
writeFileSync('src/data/common-words.js', out);
copyFileSync('node_modules/wordlist-english/Copyright', 'src/data/COMMON-WORDS-LICENSE.txt');
console.log('common words:', words.length, 'bytes:', out.length);
