// Browser check for the home screen, header, theme switch and mock interview spacing.
//   npm run build && npx vite preview --port 4173 &   then  node tests/ui/home-ui.mjs
const { chromium } = await import('playwright').catch(() => import('/opt/node-tools/node_modules/playwright/index.mjs'));
const out = [];
const check = (name, ok) => out.push(`${ok ? 'PASS' : 'FAIL'}  ${name}`);

const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 375, height: 740 } });
const errors = [];
p.on('pageerror', e => errors.push(e.message));
await p.goto('http://localhost:4173/');
await p.evaluate(() => {
  localStorage.setItem('is_hist', JSON.stringify([{ c: 'Software Developer', d: '10/14/2026', s: 7, ts: Date.now() - 864e5 }]));
  // A user who finished setup (the app has no demo profile any more).
  const me = { name: 'Test User', role: 'Software Engineer', roleKey: 'Software Engineer', edu: 'BS IT student', degree: 'BS IT student', city: 'Testcity', exp: 'fresher', skillTags: ['JavaScript'], skills: 'JavaScript', words: ['Test', 'User', 'Testcity'], setup: 1 };
  localStorage.setItem('is_profiles', JSON.stringify({ 'Test User': me }));
  localStorage.setItem('is_active', JSON.stringify('Test User'));
});
await p.reload();
await p.waitForTimeout(900);

const homeText = await p.textContent('#home');
check('home has no "Last session" card (history exists)', !/Last session/i.test(homeText) && (await p.locator('#retryLastBtn').count()) === 0);
check('header has no theme button', (await p.locator('header.bar [data-i="moon"], header.bar [onclick*="Theme"]').count()) === 0);
check('header shows logo on home', await p.isVisible('#hLogo'));
const hero = await p.$eval('.hhero', e => {
  const r = e.getBoundingClientRect();
  const tx = e.querySelector('.htx').getBoundingClientRect();
  const art = e.querySelector('.hart').getBoundingClientRect();
  const btn = e.querySelector('.hcta').getBoundingClientRect();
  return { h: r.height, row: art.left >= tx.right - 1 && art.top < tx.bottom && art.bottom > tx.top, inside: art.right <= r.right + 1, btnH: btn.height, feats: e.querySelectorAll('.hfeat .hf').length };
});
check(`home hero: text left, illustration right (one horizontal row, ${Math.round(hero.h)}px)`, hero.row && hero.inside && hero.h <= 320);
check('home hero: greeting, title, tagline, 3 features, Get Started', (await p.textContent('#hi')) === 'Test' && /Interview\s*Simulator/.test(await p.textContent('.htitle')) && (await p.textContent('.htag')) === 'Practice. Improve. Succeed.' && hero.feats === 3 && (await p.textContent('.hcta')).includes('Get Started') && hero.btnH >= 44);
const cards = await p.$$eval('#hCards .hcard', cs => cs.map(c => c.querySelector('h4').textContent));
check(`home: only one card under the hero, Question of the day (${cards.join(', ')})`, cards.join() === 'Question of the day' && (await p.locator('#hDots').count()) === 0);
const heroGap = await p.evaluate(() => document.querySelector('.hhero').getBoundingClientRect().top - document.querySelector('header.bar').getBoundingClientRect().bottom);
check(`home: no empty gap above the hero (${Math.round(heroGap)}px)`, heroGap <= 20);
check('no Alex or Khan anywhere on Home', !/\bAlex\b|\bKhan\b/.test(await p.textContent('body')));
await p.click('.hcta');
await p.waitForTimeout(400);
check('Get Started opens the Mock page', await p.isVisible('#mock'));
await p.evaluate(() => window.home());
await p.waitForTimeout(400);

const q1 = await p.textContent('.qotdq');
await p.click('#hSeg button:nth-child(3)');
await p.waitForTimeout(200);
await p.evaluate(() => window.showProfile());
await p.waitForTimeout(300);
await p.evaluate(() => window.home());
await p.waitForTimeout(500);
check('question of the day stays the same after level change', (await p.textContent('.qotdq')) === q1);
await p.reload();
await p.waitForTimeout(800);
check('question of the day stays the same after restart', (await p.textContent('.qotdq')) === q1);
const saved = await p.evaluate(() => JSON.parse(localStorage.getItem('is_qotd')));
const t = new Date();
const today = `${t.getFullYear()}-${String(t.getMonth() + 1).padStart(2, '0')}-${String(t.getDate()).padStart(2, '0')}`;
check('pick is saved for today', saved?.d === today && saved.q === q1);
await p.evaluate(() => localStorage.setItem('is_qotd', JSON.stringify({ ...JSON.parse(localStorage.getItem('is_qotd')), d: '2000-01-01' })));
await p.reload();
await p.waitForTimeout(800);
const q2 = await p.textContent('.qotdq');
check('a new day gives a different question', q2 !== q1);

await p.click('#qotdBtn');
await p.waitForTimeout(600);
check('Practice it opens that question', (await p.textContent('#pQt')).trim() === q2.trim());
check('bottom nav hidden on practice question screen', !(await p.isVisible('#nav')));
check('Practice it shows only 1 question (1 / 1, no dots)', /· 1 \/ 1$/.test((await p.textContent('#pCount')).trim()) && !(await p.isVisible('#pDots')));
await p.evaluate(() => window.pStep(1));
await p.waitForTimeout(300);
check('cannot move forward from it', (await p.textContent('#pQt')).trim() === q2.trim());
check('Finish button shown', await p.isVisible('#pDone'));
await p.click('#pFav');
await p.waitForTimeout(200);
check('favorite star works on one tap', await p.evaluate(() => document.getElementById('pFav').classList.contains('on')));

await p.evaluate(() => window.showProfile());
await p.waitForTimeout(400);
check('Profile hero has one fixed color (no gradient, no animation)', await p.evaluate(() => { const c = getComputedStyle(document.querySelector('.pcard')); return c.backgroundImage === 'none' && c.animationName === 'none'; }));
check('bottom nav visible on Profile', await p.isVisible('#nav'));
check('About you card removed', !/About you/i.test(await p.textContent('#form')) || (await p.locator('#form .sec h4', { hasText: 'About you' }).count()) === 0);
check('details hidden at first', !(await p.isVisible('#pKv')));
await p.click('#pWho');
await p.waitForTimeout(200);
check('tap on name shows About details', (await p.isVisible('#pKv')) && /Education/.test(await p.textContent('#pKv')));
await p.click('#pWho');
await p.waitForTimeout(200);
check('tap again hides them', !(await p.isVisible('#pKv')));
await p.click('#hEye');
await p.waitForTimeout(200);
check('Interview history opens on one tap', await p.isVisible('#hList'));
await p.click('#hEye');
await p.waitForTimeout(200);
check('Interview history closes on next tap', !(await p.isVisible('#hList')));
const before = await p.evaluate(() => document.documentElement.dataset.theme);
await p.click('#pTheme');
await p.waitForTimeout(200);
const after = await p.evaluate(() => document.documentElement.dataset.theme);
check('theme icon changes theme', before !== after && (await p.getAttribute('#pTheme', 'data-i')) === (after === 'dark' ? 'sun' : 'moon'));
await p.reload();
await p.waitForTimeout(700);
check('theme is remembered', (await p.evaluate(() => document.documentElement.dataset.theme)) === after);
check('header back button hides logo', await p.evaluate(() => { window.showProfile(); return true; }) && !(await p.isVisible('#hLogo')));

await p.evaluate(() => window.startMock());
await p.waitForTimeout(400);
check('mock page has level tabs and category tiles', (await p.locator('#mSeg button').count()) === 3 && (await p.locator('#mGrid .mt').count()) >= 4);
await p.click('#mGrid .mt:nth-child(2)');
await p.click('#mSeg button:nth-child(2)');
await p.waitForTimeout(300);
const pickedC = await p.getAttribute('#mGrid .mt.on', 'data-c');
check('tapping a tile selects it (one selected)', (await p.locator('#mGrid .mt.on').count()) === 1 && pickedC === (await p.getAttribute('#mGrid .mt:nth-child(2)', 'data-c')));
check('Start button says only "Start"', (await p.textContent('#mStart')).trim() === 'Start');
const tiles = await p.$$eval('#mGrid .mt', bs => bs.map(b => b.getBoundingClientRect().height));
check('tiles are big enough to tap (>= 44px)', tiles.every(h => h >= 44));
await p.reload();
await p.waitForTimeout(700);
await p.evaluate(() => window.startMock());
await p.waitForTimeout(400);
check('mock choice is remembered', (await p.getAttribute('#mGrid .mt.on', 'data-c')) === pickedC && (await p.getAttribute('#mSeg button.on', 'data-lvl')) === 'junior');
await p.click('#mStart');
await p.waitForTimeout(1200);
if (await p.isVisible('#dlg')) { await p.click('#dYes'); await p.waitForTimeout(1000); }
check('Start uses the picked type and level', await p.evaluate(() => JSON.parse(localStorage.getItem('is_scr') || '{}').lv === 'junior'));
await p.evaluate(() => { window.leaveOK = true; });
await p.evaluate(() => window.startInterview());
await p.waitForTimeout(1500);
if (await p.isVisible('#dlg')) { await p.click('#dYes'); await p.waitForTimeout(1200); }
const gap = await p.evaluate(() => {
  const q = document.querySelector('#interview .qbody').getBoundingClientRect();
  const t = document.getElementById('qText').getBoundingClientRect();
  const a = document.getElementById('ansBox').getBoundingClientRect();
  return { emptyBelowText: q.bottom - t.bottom, gapToBox: a.top - q.bottom };
});
const c0 = await p.textContent('#qCount');
await p.click('#nBtn');
await p.waitForTimeout(700);
check(`mock: Next moves exactly 1 question (${c0} -> ${await p.textContent('#qCount')})`, (await p.textContent('#qCount')).startsWith('2/'));
await p.click('[onclick="step(-1)"]');
await p.waitForTimeout(700);
check(`mock: no empty space between question and answer box (${Math.round(gap.emptyBelowText)}px + ${Math.round(gap.gapToBox)}px)`, gap.emptyBelowText <= 2 && gap.gapToBox <= 12);
const pad = await p.evaluate(() => { document.documentElement.classList.add('wv-below-bars'); const v = getComputedStyle(document.querySelector('header.bar')).paddingTop; document.documentElement.classList.remove('wv-below-bars'); return v; });
check(`header: no status bar padding when WebView starts below it (${pad})`, pad === '6px');
check('no horizontal scroll', await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
check('no page errors', errors.length === 0);
await b.close();
console.log(out.join('\n'));
if (out.some(l => l.startsWith('FAIL'))) process.exit(1);
